# ADI first-run setup: local environment files only.
# Safe to re-run: nothing is overwritten.
[CmdletBinding()]
param()

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$backend = Join-Path $root "backend"
$frontend = Join-Path $root "frontend"
$envFile = Join-Path $backend ".env"
$frontendEnv = Join-Path $frontend ".env.local"

function New-RandomBase64([int]$Bytes) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($buffer)
    $rng.Dispose()
    return [Convert]::ToBase64String($buffer)
}

function New-FernetKey {
    $urlSafe = (New-RandomBase64 32).Replace("+", "-").Replace("/", "_")
    return $urlSafe
}

if (-not (Test-Path $backend)) {
    throw "Backend folder not found at $backend"
}

if (Test-Path $envFile) {
    Write-Host "Backend .env already exists - leaving it untouched." -ForegroundColor Yellow
} else {
    $secret = New-RandomBase64 48
    $existingKeyFile = Join-Path $backend "data\.encryption_key"
    if (Test-Path $existingKeyFile) {
        $fernet = (Get-Content $existingKeyFile -Raw).Trim()
        Write-Host "Reusing the existing local encryption key." -ForegroundColor Green
    } else {
        $fernet = New-FernetKey
    }
    $content = @"
# ADI backend configuration (generated by setup.ps1)
APP_ENV=development
APP_SECRET_KEY=$secret
APP_ENCRYPTION_KEY=$fernet

# Optional overrides
# DATABASE_URL=sqlite:///C:/path/to/adi.db
# DATA_DIR=C:/path/to/adi-data
# WORKSPACE_DIR=C:/path/to/adi-workspace
# CORS_ORIGINS=http://localhost:3000,http://127.0.0.1:3000
# PROVIDER_TIMEOUT=90
# COMMAND_TIMEOUT=30
# MAX_OUTPUT_BYTES=65536
# MAX_UPLOAD_MB=25
# APP_ACCESS_TOKEN=
"@
    Set-Content -Path $envFile -Value $content -Encoding UTF8
    Write-Host "Created backend/.env with a fresh encryption key." -ForegroundColor Green
}

if (Test-Path $frontendEnv) {
    Write-Host "frontend/.env.local already exists - leaving it untouched." -ForegroundColor Yellow
} else {
    Set-Content -Path $frontendEnv -Value "NEXT_PUBLIC_ADI_API_URL=http://127.0.0.1:8000" -Encoding UTF8
    Write-Host "Created frontend/.env.local." -ForegroundColor Green
}

Write-Host ""
Write-Host "Setup complete. Next: .\install.ps1 then .\start.ps1" -ForegroundColor Cyan
